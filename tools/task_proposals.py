def dist(n):
    d = {0: 1}
    for _ in range(n):
        nd = defaultdict(int)
        for s, c in d.items():
            for f in range(1, 7): nd[s + f] += c
        d = nd
    return d

def prob(cond, n):
    d = dist(n); t = 6 ** n
    op, a, b = cond
    ok = lambda s: (s >= a) if op == '≥' else (s <= a) if op == '≤' else (a <= s <= b)
    return sum(c for s, c in d.items() if ok(s)) / t

def fmt(cond):
    op, a, b = cond
    return f'≥{a}' if op == '≥' else f'≤{a}' if op == '≤' else f'{a}～{b}'

