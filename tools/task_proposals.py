SAL = 1.4  # 每顆骰子的平均薪資

def pf(x):
    return "±0（打平）" if abs(x) < 0.05 else f"{x:+.1f}"

def ease(cond, k):
    op, a, b = cond
    if op == '≥': return ('≥', a - k, 0)
    if op == '≤': return ('≤', a + k, 0)
    return ('~', a - (k // 2 + k % 2), b + k // 2)

def exp_tries(cond, n, epic=False):
    if epic: return 1.0
    e, surv = 0.0, 1.0
    for k in range(15):
        e += surv; surv *= 1 - prob(ease(cond, k), n)
    return e

